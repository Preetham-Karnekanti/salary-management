
-- Countries
CREATE TABLE countries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code VARCHAR(2) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    default_currency_code VARCHAR(3) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Departments
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Employees
CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(30) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    country_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    job_title VARCHAR(150) NOT NULL,
    employment_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    hire_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_employee_country
        FOREIGN KEY (country_id) REFERENCES countries(id),

    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id) REFERENCES departments(id),

    CONSTRAINT chk_employee_status
        CHECK (employment_status IN ('ACTIVE', 'INACTIVE', 'ON_LEAVE'))
);

-- Salary records (current and historical)
CREATE TABLE salaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    base_salary DECIMAL(19, 4) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL,

    CONSTRAINT fk_salary_employee
        FOREIGN KEY (employee_id) REFERENCES employees(id),

    CONSTRAINT uq_employee_salary_effective_date
        UNIQUE (employee_id, effective_from),

    CONSTRAINT chk_salary_amount
        CHECK (base_salary >= 0),

    CONSTRAINT chk_salary_effective_dates
        CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

-- Indexes
CREATE INDEX idx_employee_country
    ON employees(country_id);

CREATE INDEX idx_employee_department
    ON employees(department_id);

CREATE INDEX idx_employee_status
    ON employees(employment_status);

CREATE INDEX idx_employee_name
    ON employees(first_name, last_name);

CREATE INDEX idx_salary_employee
    ON salaries(employee_id);

CREATE INDEX idx_salary_effective_dates
    ON salaries(effective_from, effective_to);
